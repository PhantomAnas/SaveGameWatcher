"""Built-in list of games and where they keep their saves.  No Qt.

The list lives in data/games.json (generated by scripts/build_catalog.py).
Paths in it use placeholders that are filled in for whoever is logged in:

    {DOCUMENTS} {SAVEDGAMES} {APPDATA} {LOCALAPPDATA} {LOCALLOW} {PUBLIC}
    {PROGRAMDATA} {HOME} {STEAM} {UBISOFT} {GAMEDIR}  and  * (any one folder)

`detect(game)` expands every known location of a game and reports which of
them exist on this PC, how many files they hold and when the newest one was
written - so after playing and saving once, the right folder stands out.
"""

from __future__ import annotations

import glob
import json
import os
import re
import sys
import urllib.request
from dataclasses import dataclass, field
from datetime import datetime
from functools import lru_cache

CATALOG_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "games.json")
TOKEN_RE = re.compile(r"\{([A-Z]+)\}")
SCAN_FILE_LIMIT = 20000


@dataclass(frozen=True)
class Location:
    label: str
    path: str  # template with placeholders


@dataclass(frozen=True)
class Game:
    id: str
    name: str
    steam: int | None
    locations: tuple[Location, ...]
    install_dirs: tuple[str, ...] = ()


@dataclass
class Candidate:
    label: str
    template: str
    path: str                 # expanded; may still contain * when nothing matched
    exists: bool = False      # folder exists and holds at least one file
    files: int = 0
    newest: datetime | None = None
    extra: dict = field(default_factory=dict)


# ------------------------------------------------------------------ list

@lru_cache(maxsize=4)
def load_catalog(path: str = CATALOG_PATH) -> tuple[Game, ...]:
    try:
        with open(path, "r", encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return ()
    games = []
    for g in data.get("games", []):
        try:
            games.append(Game(
                id=str(g["id"]), name=str(g["name"]), steam=g.get("steam"),
                locations=tuple(Location(str(loc["label"]), str(loc["path"]))
                                for loc in g["locations"]),
                install_dirs=tuple(g.get("install_dirs", ())),
            ))
        except (KeyError, TypeError):
            continue
    return tuple(games)


def find_game(game_id: str) -> Game | None:
    return next((g for g in load_catalog() if g.id == game_id), None)


def _words(text: str) -> list[str]:
    return re.sub(r"[^a-z0-9 ]+", " ", text.lower().replace("'", "")).split()


def search(query: str, games: tuple[Game, ...] | None = None) -> list[Game]:
    """Games whose name contains every word of `query` (any order, any case)."""
    games = load_catalog() if games is None else games
    words = _words(query)
    out = []
    for g in games:
        name = " " + " ".join(_words(g.name)) + " "
        if all(w in name for w in words):
            out.append(g)
    return out


# ------------------------------------------------------- known folders

def _known_folder(guid: str) -> str | None:
    """Windows known-folder path (follows OneDrive / moved Documents)."""
    if sys.platform != "win32":
        return None
    try:
        import ctypes
        from ctypes import wintypes

        class GUID(ctypes.Structure):
            _fields_ = [("Data1", wintypes.DWORD), ("Data2", wintypes.WORD),
                        ("Data3", wintypes.WORD), ("Data4", ctypes.c_ubyte * 8)]

        h = guid.strip("{}").split("-")
        tail = bytes.fromhex(h[3] + h[4])
        g = GUID(int(h[0], 16), int(h[1], 16), int(h[2], 16), (ctypes.c_ubyte * 8)(*tail))
        out = ctypes.c_wchar_p()
        if ctypes.windll.shell32.SHGetKnownFolderPath(ctypes.byref(g), 0, None,
                                                      ctypes.byref(out)) != 0:
            return None
        path = out.value
        ctypes.windll.ole32.CoTaskMemFree(out)
        return path
    except Exception:  # noqa: BLE001 - fall back to the usual location
        return None


def _registry(root: str, key: str, value: str) -> str | None:
    if sys.platform != "win32":
        return None
    try:
        import winreg

        hive = {"HKCU": winreg.HKEY_CURRENT_USER, "HKLM": winreg.HKEY_LOCAL_MACHINE}[root]
        with winreg.OpenKey(hive, key) as k:
            return str(winreg.QueryValueEx(k, value)[0])
    except OSError:
        return None


def steam_root() -> str:
    for root, key, value in (("HKCU", r"Software\Valve\Steam", "SteamPath"),
                             ("HKLM", r"SOFTWARE\WOW6432Node\Valve\Steam", "InstallPath"),
                             ("HKLM", r"SOFTWARE\Valve\Steam", "InstallPath")):
        path = _registry(root, key, value)
        if path and os.path.isdir(path):
            return os.path.normpath(path)
    if sys.platform == "win32":
        return r"C:\Program Files (x86)\Steam"
    return os.path.expanduser("~/.steam/steam")


def ubisoft_root() -> str:
    path = _registry("HKLM", r"SOFTWARE\WOW6432Node\Ubisoft\Launcher", "InstallDir")
    if path and os.path.isdir(path):
        return os.path.normpath(path)
    return r"C:\Program Files (x86)\Ubisoft\Ubisoft Game Launcher"


def steam_libraries(steam: str | None = None) -> list[str]:
    """Every Steam library folder (the install folder plus extra drives)."""
    steam = steam or steam_root()
    libs = [steam]
    try:
        with open(os.path.join(steam, "steamapps", "libraryfolders.vdf"), encoding="utf-8",
                  errors="replace") as fh:
            text = fh.read()
        for raw in re.findall(r'"path"\s+"([^"]+)"', text):
            path = os.path.normpath(raw.replace("\\\\", "\\"))
            if path.lower() not in (p.lower() for p in libs):
                libs.append(path)
    except OSError:
        pass
    return libs


def known_folders() -> dict[str, str]:
    home = os.path.expanduser("~")
    env = os.environ
    return {
        "HOME": home,
        "DOCUMENTS": _known_folder("{FDD39AD0-238F-46AF-ADB4-6C85480369C7}")
        or os.path.join(home, "Documents"),
        "SAVEDGAMES": _known_folder("{4C5C32FF-BB9D-43B0-B5B4-2D72E54EAAA4}")
        or os.path.join(home, "Saved Games"),
        "APPDATA": env.get("APPDATA") or os.path.join(home, "AppData", "Roaming"),
        "LOCALAPPDATA": env.get("LOCALAPPDATA") or os.path.join(home, "AppData", "Local"),
        "LOCALLOW": _known_folder("{A520A1A4-1780-4FF6-BD18-167343C5AF16}")
        or os.path.join(home, "AppData", "LocalLow"),
        "PUBLIC": env.get("PUBLIC") or os.path.join(os.path.dirname(home), "Public"),
        "PROGRAMDATA": env.get("PROGRAMDATA") or r"C:\ProgramData",
        "STEAM": steam_root(),
        "UBISOFT": ubisoft_root(),
    }


# ------------------------------------------------------------- expanding

def fill(template: str, folders: dict[str, str], gamedir: str | None = None) -> str | None:
    """Template with every placeholder filled in (* stays).  None if a
    placeholder cannot be filled."""
    missing = False

    def sub(m: re.Match) -> str:
        nonlocal missing
        name = m.group(1)
        value = gamedir if name == "GAMEDIR" else folders.get(name)
        if not value:
            missing = True
            return ""
        return value.replace("\\", "/")

    out = TOKEN_RE.sub(sub, template)
    return None if missing else os.path.normpath(out)


def _glob(pattern: str) -> list[str]:
    """Glob where only bare * segments are wildcards; other characters such as
    [ ] in folder names are taken literally."""
    parts = pattern.replace("\\", "/").split("/")
    safe = "/".join(p if p == "*" else glob.escape(p) for p in parts)
    return sorted(os.path.normpath(p) for p in glob.glob(safe))


def expand(game: Game, location: Location, folders: dict[str, str] | None = None) -> list[str]:
    """Real folders this location stands for on this PC.  Paths without a
    wildcard are returned whether they exist or not; wildcards only expand to
    folders that exist.  A location naming a file yields its folder."""
    folders = folders if folders is not None else known_folders()
    bases: list[str | None] = [None]
    if "{GAMEDIR}" in location.path:
        bases = [os.path.join(lib, "steamapps", "common", d)
                 for lib in steam_libraries(folders.get("STEAM")) for d in game.install_dirs]
    out: list[str] = []
    for base in bases:
        path = fill(location.path, folders, base)
        if path is None:
            continue
        # A * stands for a folder (a user or account id), never a loose file.
        found = [p for p in _glob(path) if os.path.isdir(p)] if "*" in path else [path]
        for p in found:
            if os.path.isfile(p):
                p = os.path.dirname(p)
            if p not in out:
                out.append(p)
    return out


def scan_folder(path: str) -> tuple[int, datetime | None]:
    """(file count, newest modification time) below `path`."""
    files = 0
    newest = 0.0
    for root, _dirs, names in os.walk(path):
        for name in names:
            try:
                mtime = os.stat(os.path.join(root, name)).st_mtime
            except OSError:
                continue
            files += 1
            newest = max(newest, mtime)
            if files >= SCAN_FILE_LIMIT:
                return files, datetime.fromtimestamp(newest)
    return files, (datetime.fromtimestamp(newest) if files else None)


def detect(game: Game, folders: dict[str, str] | None = None) -> list[Candidate]:
    """Every known location of `game`, found ones first (newest save first)."""
    folders = folders if folders is not None else known_folders()
    found: list[Candidate] = []
    missing: list[Candidate] = []
    seen: set[str] = set()
    for loc in game.locations:
        paths = expand(game, loc, folders)
        if not paths:
            shown = fill(loc.path, folders, "<game folder>") or loc.path
            missing.append(Candidate(loc.label, loc.path, shown))
            continue
        for path in paths:
            key = os.path.normcase(path)
            if key in seen:
                continue
            seen.add(key)
            cand = Candidate(loc.label, loc.path, path)
            if os.path.isdir(path):
                cand.files, cand.newest = scan_folder(path)
                cand.exists = cand.files > 0
            (found if cand.exists else missing).append(cand)
    found.sort(key=lambda c: c.newest or datetime.min, reverse=True)
    return found + missing


# --------------------------------------------------------- search by name

# Words that say nothing about which game a folder belongs to.
_STOP_WORDS = {"the", "a", "an", "of", "and", "edition", "definitive", "remastered",
               "enhanced", "complete", "goty", "deluxe", "directors", "cut", "game"}
_SAVE_DIR_RE = re.compile(r"^(save|saves|saved|savegames?|save ?games|gamesaves|savedata|"
                          r"saved ?games|profiles?|storage)$", re.I)


def name_pattern(name: str) -> re.Pattern | None:
    """Regex matching folder names that spell the game's name, ignoring case,
    spaces and punctuation: 'The Witcher 3: Wild Hunt' matches 'The Witcher 3',
    'TheWitcher3', 'witcher_3'.  The subtitle after ':' or ' - ' is optional."""
    main = re.split(r":| - ", name, maxsplit=1)[0]
    words = [w for w in _words(main) if w not in _STOP_WORDS] or _words(main)
    if not words or len("".join(words)) < 3:
        return None
    return re.compile(r"[\W_]*".join(re.escape(w) for w in words), re.I)


def _search_roots(folders: dict[str, str]) -> list[tuple[str, int]]:
    """(folder, how deep to look) - the places games put their saves."""
    docs = folders["DOCUMENTS"]
    return [
        (docs, 3),                                    # Documents\My Games\<game>, Documents\Rockstar Games\<game>
        (folders["SAVEDGAMES"], 3),
        (folders["APPDATA"], 2),
        (folders["LOCALAPPDATA"], 2),
        (folders["LOCALLOW"], 2),
        (os.path.join(folders["PUBLIC"], "Documents"), 3),
    ]


def _walk_dirs(root: str, depth: int):
    """Folders below `root`, at most `depth` levels down, skipping junctions."""
    stack = [(root, 0)]
    while stack:
        path, level = stack.pop()
        try:
            entries = list(os.scandir(path))
        except OSError:
            continue
        for e in entries:
            try:
                if not e.is_dir(follow_symlinks=False):
                    continue
            except OSError:
                continue
            yield e.path, e.name
            if level + 1 < depth:
                stack.append((e.path, level + 1))


def _save_subfolder(folder: str, depth: int = 4) -> str | None:
    """A folder below `folder` that is named like a save folder and holds files."""
    for path, name in _walk_dirs(folder, depth):
        if _SAVE_DIR_RE.match(name):
            try:
                if any(True for _ in os.scandir(path)):
                    return path
            except OSError:
                continue
    return None


def search_by_name(name: str, folders: dict[str, str] | None = None,
                   limit: int = 25) -> list[Candidate]:
    """Look for this game's save folder on the PC by its name, for games that
    are not in the built-in list.  Folders whose name spells the game's name
    are listed (with a save-looking subfolder preferred when there is one),
    newest files first.  Results are suggestions for the player to inspect."""
    pattern = name_pattern(name)
    if pattern is None:
        return []
    folders = folders if folders is not None else known_folders()
    hits: list[Candidate] = []
    seen: set[str] = set()
    for root, depth in _search_roots(folders):
        if not os.path.isdir(root):
            continue
        for path, dirname in _walk_dirs(root, depth):
            if not pattern.search(dirname):
                continue
            target = _save_subfolder(path) or path
            key = os.path.normcase(target)
            if key in seen or any(key.startswith(s + os.sep) for s in seen):
                continue
            seen.add(key)
            cand = Candidate("Found by name", "", target)
            cand.files, cand.newest = scan_folder(target)
            cand.exists = cand.files > 0
            if cand.exists:
                hits.append(cand)
    hits.sort(key=lambda c: c.newest or datetime.min, reverse=True)
    return hits[:limit]


# ---------------------------------------------------------------- covers

def cover_cache_dir() -> str:
    from platformdirs import user_cache_dir

    return os.path.join(user_cache_dir("SaveWatch", appauthor=False), "covers")


def cached_cover(steam_id: int | None) -> str | None:
    if not steam_id:
        return None
    path = os.path.join(cover_cache_dir(), f"{int(steam_id)}.jpg")
    return path if os.path.isfile(path) and os.path.getsize(path) > 0 else None


def fetch_cover(steam_id: int | None, timeout: float = 8.0) -> str | None:
    """Download the game's cover from Steam's public image server (once;
    cached afterwards).  Returns the cached file, or None offline."""
    if not steam_id:
        return None
    cached = cached_cover(steam_id)
    if cached:
        return cached
    folder = cover_cache_dir()
    os.makedirs(folder, exist_ok=True)
    target = os.path.join(folder, f"{int(steam_id)}.jpg")
    for name in ("library_600x900.jpg", "header.jpg"):
        url = f"https://cdn.cloudflare.steamstatic.com/steam/apps/{int(steam_id)}/{name}"
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "SaveWatch"})
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                data = resp.read(3_000_000)
        except Exception:  # noqa: BLE001 - offline, 404, ...
            continue
        if data[:3] == b"\xff\xd8\xff" or data[:8] == b"\x89PNG\r\n\x1a\n":
            tmp = target + ".tmp"
            with open(tmp, "wb") as fh:
                fh.write(data)
            os.replace(tmp, target)
            return target
    return None
